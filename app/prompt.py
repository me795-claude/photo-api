"""Перечень проверок, промпт и JSON Schema ответа LLM."""
from __future__ import annotations

from collections import OrderedDict

# test_type -> краткое название требования (по документу «Требование к фото на пропуск»)
TEST_TYPES = OrderedDict(
    [
        ("format", "Формат и пропорции"),
        ("quality", "Качество снимка"),
        ("lighting_color", "Свет, контраст и цвет"),
        ("background", "Фон"),
        ("headwear", "Головной убор"),
        ("head_position", "Положение головы"),
        ("gaze_expression", "Взгляд и выражение лица"),
        ("face_eyes", "Лицо и глаза"),
        ("glasses", "Очки"),
    ]
)

SUCCESS = "successed"
FAILED = "failed"

SYSTEM_PROMPT = """Ты — строгая система контроля фотографий на пропуск. Оцени изображение по 9 пунктам и верни JSON.

Пункты (test_type — критерий):
1. format — портретный кадр с пропорциями 35×45 мм (ширина:высота ≈ 7:9). Голова от подбородка до макушки (без учёта волос) занимает 71–80% высоты кадра (32–36 мм из 45). Голова целиком в кадре, по центру, над головой небольшой отступ. failed, если голова слишком крупная (обрезана макушка или подбородок, лицо почти во весь кадр) или слишком мелкая (видны грудь, плечи и много пустого фона).
2. quality — снимок чёткий: нет размытия, расфокусировки, шума, сильных артефактов сжатия, сгибов, царапин, пятен, грязи.
3. lighting_color — фото цветное (не ч/б, не сепия); лицо освещено равномерно; нет резких теней на лице и фоне; нет пересвета (белые «выжженные» участки лица) и затемнения (лицо слишком тёмное, детали не видны).
4. background — фон однотонный и ровный: без узоров, пейзажа, предметов, мебели, других людей и их частей, без резкого градиента.
5. headwear — нет головного убора (шапка, кепка, шляпа, панама, капюшон, платок, бандана, повязка и т.п.).
6. head_position — голова держится прямо, лицо развёрнуто анфас к камере; нет поворота, наклона вбок, запрокидывания или опускания головы; голову никто не поддерживает руками.
7. gaze_expression — человек смотрит прямо в объектив (зрачки по центру глаз, не в сторону); выражение лица нейтральное; рот закрыт; нет улыбки с зубами и гримас.
8. face_eyes — лицо видно полностью: не закрыто волосами, руками, предметами; оба глаза открыты и хорошо видны.
9. glasses — если очков нет — successed. Если очки есть: оправа тонкая и не закрывает глаза, стёкла прозрачные, без тонировки и без бликов, глаза за стёклами хорошо видны. Иначе failed.

Правила ответа:
- Ровно 9 объектов в массиве "checks", по одному на каждый test_type, в порядке списка выше.
- "result": только "successed" или "failed".
- "comment": при failed — одно-два коротких предложения на русском: что именно не так и как исправить. При successed — пустая строка "".
- Оценивай каждый пункт независимо; один дефект может провалить несколько пунктов (например, тёмные очки → glasses и face_eyes).
- Если по пункту нельзя уверенно судить (плохо видно) — failed с объяснением.
- Если на фото нет человека или людей больше одного — все пункты failed с этим комментарием.
- Ответ — только JSON-объект, без пояснений и без markdown."""

USER_PROMPT = "Проверь это фото на пропуск по всем 9 пунктам и верни только JSON."

RESPONSE_SCHEMA = {
    "type": "object",
    "additionalProperties": False,
    "required": ["checks"],
    "properties": {
        "checks": {
            "type": "array",
            "minItems": len(TEST_TYPES),
            "maxItems": len(TEST_TYPES),
            "items": {
                "type": "object",
                "additionalProperties": False,
                "required": ["test_type", "result", "comment"],
                "properties": {
                    "test_type": {"type": "string", "enum": list(TEST_TYPES)},
                    "result": {"type": "string", "enum": [SUCCESS, FAILED]},
                    "comment": {"type": "string"},
                },
            },
        }
    },
}
